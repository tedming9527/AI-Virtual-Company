def digest(data): return hashlib.sha256(data).hexdigest()
def read(path): return json.loads(Path(path).read_text())
def safe(path):
    path = Path(os.path.abspath(path))
    for p in [path, *path.parents]:
        if p.is_symlink(): raise ValueError(f'Symlink refused: {p}')
    return path

def inventory(path):
    path = safe(path)
    if not path.exists(): return {}
    if path.is_file(): return {'': digest(path.read_bytes())}
    result = {}
    for p in sorted(path.rglob('*')):
        safe(p)
        if p.is_file(): result[str(p.relative_to(path))] = digest(p.read_bytes())
        elif not p.is_dir(): raise ValueError('Unsupported file type')
    return result

def atomic(path, data):
    path = safe(path); path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + '.' + uuid.uuid4().hex + '.tmp')
    try:
        with open(tmp, 'xb') as f:
            os.chmod(tmp, 0o600); f.write(data); f.flush(); os.fsync(f.fileno())
        os.replace(tmp, path)
    finally: tmp.unlink(missing_ok=True)

def save(path, value): atomic(path, (json.dumps(value, ensure_ascii=False, indent=2)+'\n').encode())
def copy_verified(source, target, snapshot=None):
    source, target = safe(source), safe(target)
    snapshot = inventory(source) if snapshot is None else snapshot
    if source.is_file():
        atomic(target, source.read_bytes()); target.chmod(source.stat().st_mode & 0o777)
    else:
        target.mkdir(parents=True, exist_ok=False)
        for rel in snapshot:
            atomic(target/rel, (source/rel).read_bytes()); (target/rel).chmod((source/rel).stat().st_mode & 0o777)
    if inventory(target) != snapshot or inventory(source) != snapshot: raise ValueError('Copy/source verification failed')
    return snapshot

def remove(path):
    safe(path)
    if path.is_dir(): shutil.rmtree(path)
    else: path.unlink(missing_ok=True)

def owned_hooks(document, home):
    def is_owned(hook):
        try:parts=shlex.split(hook.get('command',''))
        except ValueError:return False
        if str(home/'ted-avc-manager-hook.sh') in parts:return True
        for script,flag in [('codex-hook.js','--ted-avc-manager-footer'),('execution-hook.js','--ted-avc-manager-execution')]:
            if flag in parts and any(p.endswith('/src/'+script) and ('/ted-avc-manager/' in p or '/avc-pack-manager/' in p) for p in parts):return True
        return False
    out = json.loads(json.dumps(document)); out.setdefault('hooks', {})
    for event, groups in out['hooks'].items():
        kept=[]
        for group in groups:
            hooks=[h for h in group.get('hooks',[]) if not is_owned(h)]
            if hooks: kept.append({**group,'hooks':hooks})
        out['hooks'][event]=kept
    return out

def replace_mcp(text, block):
    previous=tomllib.loads(text); lines=[]; skip=False
    for line in text.splitlines(keepends=True):
        if line.lstrip().startswith('['):
            header=line.strip().split(' #',1)[0]
            try: parsed=tomllib.loads(header+'\n')
            except tomllib.TOMLDecodeError: raise ValueError('Unsupported TOML table header')
            skip=bool(set(parsed.get('mcp_servers',{})) & {'ted-avc-manager','pack-manager'})
        if not skip: lines.append(line)
    result=''.join(lines).rstrip()+'\n\n'+block
    after=tomllib.loads(result)
    for doc in [previous,after]:
        for key in ['ted-avc-manager','pack-manager']: doc.get('mcp_servers',{}).pop(key,None)
        if doc.get('mcp_servers') == {}: doc.pop('mcp_servers')
    if previous!=after: raise ValueError('Unrelated MCP/config content would change')
    return result

def replace_rules(text, block):
    if text.startswith(LEGACY_RULE): return block+'\n'
    if BEGIN in text or END in text:
        if text.count(BEGIN)!=1 or text.count(END)!=1 or text.index(BEGIN)>text.index(END): raise ValueError('Ambiguous owned rules')
        return text[:text.index(BEGIN)]+block+text[text.index(END)+len(END):]
    return text.rstrip()+'\n\n'+block+'\n'

def alive(pid):
    try: os.kill(int(pid),0); return True
    except ProcessLookupError: return False

@contextlib.contextmanager
def locked(home):
    lock=safe(home/'.ted-avc-manager-rebuild.lock')
    lock.mkdir() # Never silently steal a transaction lock.
    save(lock/'owner.json',{'pid':os.getpid()})
    try:
        activity=safe(home/'.ted-avc-manager-activity')
        if activity.exists():
            for p in activity.iterdir():
                safe(p)
                if alive(p.name.split('-',1)[0]): raise ValueError('Client writer active; rebuild postponed')
                p.unlink()
        yield
    finally: remove(lock)

