def legacy_targets(home, user_home):
    result={}
    # Explicit migration list, with identity checks, not a broad home-directory sweep.
    for family in ['ted-avc-manager','avc-pack-manager']:
        lib=safe(user_home/'.local/lib'/family)
        if lib.exists():
            for p in sorted(lib.iterdir()):
                if not re.fullmatch(r'\d+\.\d+\.\d+',p.name): raise ValueError('Unknown legacy library entry')
                meta=read(p/'package.json')
                if meta.get('name') not in ['ted-avc-manager','avc-pack-manager','pack-manager']: raise ValueError('Legacy package identity conflict')
                inventory(p);result['legacy/'+family+'/'+p.name]=p
    for name in ['ted-avc-manager','pack-manager']:
        p=safe(user_home/'.local/bin'/name)
        if p.exists():
            text=p.read_text()
            if not ('/src/cli.js' in text and ('/ted-avc-manager/' in text or '/avc-pack-manager/' in text)): raise ValueError('Unowned launcher conflict')
            result['legacy/bin/'+name]=p
    return result

def ownership(home, user_home, migrate):
    result={}
    base=safe(home/OWNER)
    if base.exists():
        m=read(base/'manifest.json')
        if m.get('schema')!=SCHEMA or m.get('owner')!=OWNER: raise ValueError('Missing or invalid owned manifest')
        result['environment']=base
    bridge=safe(home/'skills/ted-avc-manager')
    if bridge.exists():
        if read(bridge/'meta.json').get('name')!=OWNER: raise ValueError('Unowned bridge conflict')
        result['bridge']=bridge
    command_skill=safe(home/'skills/ted')
    if command_skill.exists():
        if 'environment' not in result or not m.get('commandSkillFiles') or read(command_skill/'meta.json').get('name')!='ted': raise ValueError('Unowned ted skill conflict; preserve existing user skill')
        result['command-skill']=command_skill
    skills=safe(home/'skills')
    if skills.exists():
        for p in skills.glob('ted-avc-user-*'):
            if read(p/'.avc-owned.json').get('owner')!=OWNER: raise ValueError('Unowned import namespace conflict')
            result['imports/'+p.name]=p
    if migrate: result.update(legacy_targets(home,user_home))
    return result

