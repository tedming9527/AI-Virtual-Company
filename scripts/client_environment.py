def recover(home,user_home=None):
    home=safe(home);user_home=safe(user_home or Path.home());tx=safe(home/'.ted-avc-manager-transaction');j=read(tx/'journal.json')
    if j.get('schema')!='avc.client-transaction.v1': raise ValueError('Invalid transaction')
    # Only recovery of a recorded transaction may reclaim locks from a proven dead writer.
    for lock in [home/'.ted-avc-manager-rebuild.lock',safe(j['personal'])/'experience/.avc/asset-lifecycle.lock']:
        if lock.exists():
            owner=read(safe(lock/'owner.json'))
            if alive(owner['pid']):raise ValueError('Transaction writer still alive; do not steal lock')
            remove(lock)
    with locked(home), personal_locked(safe(j['personal'])):
        allowed={str(home/OWNER)}
        allowed.add(str(home/'skills/ted-avc-manager'))
        allowed.add(str(home/'skills/ted'))
        for p in (tx/'backup/imports').glob('*') if (tx/'backup/imports').exists() else []: allowed.add(str(home/'skills'/p.name))
        for k,p in j['targets'].items():
            target=safe(p)
            legacy=False
            # Validate legacy against the exact backup layout, never arbitrary manifest paths.
            if k.startswith('legacy/'):
                parts=Path(k).parts
                expected=user_home/'.local'/('bin' if parts[1]=='bin' else 'lib')/Path(*parts[1:]) if parts[1]!='bin' else user_home/'.local/bin'/parts[2]
                legacy=target==expected
            if str(target) not in allowed and not legacy: raise ValueError('Recovery path outside owned scope')
        if j['status']=='committed': remove(tx);return {'status':'committed-cleanup-complete'}
        if j['status']=='switching':
            for k,p in j['targets'].items():
                current=inventory(Path(p));accepted=[j['snapshots'][k],{}]
                if k=='environment':accepted.append(j['newEnvironment'])
                if k=='bridge':accepted.append(j['newBridge'])
                if k=='command-skill':accepted.append(j.get('newCommandSkill',{}))
                if current not in accepted:raise ValueError('Client changed after interruption; preserve and resolve before recovery')
            new_targets=[('environment',home/OWNER,j['newEnvironment']),('bridge',home/'skills/ted-avc-manager',j['newBridge'])]
            if 'newCommandSkill' in j:new_targets.append(('command-skill',home/'skills/ted',j['newCommandSkill']))
            for k,path,expected in new_targets:
                if k not in j['targets'] and inventory(path) not in [{},expected]:raise ValueError('New client files changed after interruption')
            for n,existed in j['shared'].items():
                current=inventory(home/n).get('')
                if current not in [j['sharedBefore'][n],j.get('sharedAfter',{}).get(n)]:raise ValueError('Shared config changed after interruption; do not overwrite')
            remove(home/OWNER);remove(home/'skills/ted-avc-manager')
            if 'newCommandSkill' in j:remove(home/'skills/ted')
            for k,p in j['targets'].items():
                remove(Path(p));copy_verified(tx/'backup'/k,Path(p))
            for n,existed in j['shared'].items():
                if n not in ['config.toml','hooks.json','AGENTS.md','ted-avc-manager-hook.cjs','ted-avc-manager-hook.sh']: raise ValueError('Invalid shared recovery path')
                remove(home/n)
                if existed:copy_verified(tx/'shared'/n,home/n)
        personal=safe(j['personal']);target=personal/'preset/avc-client-baseline'
        for e in j.get('archiveEdits',[]):
            file=safe(personal/e['relative'])
            if not (file.is_relative_to(personal/'staging/client-recovery') or file.is_relative_to(personal/'experience/.avc')):raise ValueError('Invalid observation recovery path')
