import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
const root=path.dirname(new URL(import.meta.url).pathname);
const base=fs.mkdtempSync('/tmp/ted-bootstrap-');
for(const f of ['AGENTS.md','COMPANY.md','INITIALIZATION_POLICY.md','PROJECT_BINDING_POLICY.md','ROUTER.md','MEMORY_POLICY.md','LEARNING_POLICY.md','DELIVERY_POLICY.md','KNOWLEDGE_POLICY.md','METRICS_POLICY.md','EVALUATION_POLICY.md','employees','knowledge','templates','scripts','skills','memory'])fs.cpSync(path.join(root,f),path.join(base,f),{recursive:true});
for(const f of ['inbox','schedule'])fs.mkdirSync(path.join(base,f));
const run=()=>{const r=spawnSync('/bin/zsh',[path.join(base,'scripts/check-company-bootstrap.sh')],{encoding:'utf8',env:{...process.env,AI_VIRTUAL_COMPANY_ROOT:base}});return {exit:r.status,stdout:r.stdout,stderr:r.stderr}};
const normal=run();
const profile=path.join(base,'employees/frontend-expert/PROFILE.md');
fs.renameSync(profile,profile+'.hold');
const missingProfile=run();
fs.renameSync(profile+'.hold',profile);
fs.renameSync(path.join(base,'employees/backend-expert'),path.join(base,'backend-held'));
const missingRole=run();
fs.renameSync(path.join(base,'backend-held'),path.join(base,'employees/backend-expert'));
const companyBody=path.join(base,'knowledge/research-source-governance.md');
fs.appendFileSync(companyBody,'\n<!-- synthetic stale company source -->\n');
const q=spawnSync(process.execPath,[path.join(root,'scripts/check-knowledge.mjs'),base],{encoding:'utf8'});
const rows=[{name:'normal_bootstrap',pass:normal.exit===0,...normal},{name:'missing_profile_rejected',pass:missingProfile.exit===1&&missingProfile.stderr.includes('frontend-expert/PROFILE.md'),...missingProfile},{name:'missing_entire_role_rejected',pass:missingRole.exit===1&&missingRole.stderr.includes('backend-expert/PROFILE.md'),...missingRole},{name:'company_source_drift_rejected',pass:q.status===1&&q.stdout.includes('STALE'),exit:q.status,stdout:q.stdout,stderr:q.stderr}];
fs.writeFileSync(path.join(root,'results/bootstrap-negatives.json'),JSON.stringify({fixture:base,tests:rows,limits:'Only disposable fixture mutations; not platform permission testing'},null,2)+'\n');
console.log(JSON.stringify(rows.map(x=>({name:x.name,pass:x.pass})),null,2));
process.exitCode=rows.every(x=>x.pass)?0:1;
